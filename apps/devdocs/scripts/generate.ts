// Build hook for generated content (ADR 0026, ADR 0030). Runs before `astro build` and `astro dev`.
//
// Writes the /api/v1 OpenAPI document from the API's code (`pnpm --filter @necodoc/api openapi`)
// into src/generated/openapi.json, which starlight-openapi renders as the API reference, and
// copies each SDK's README (ADR 0041) into its page. Nothing here is written by hand.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "src/generated/openapi.json");
mkdirSync(dirname(specPath), { recursive: true });

execFileSync("pnpm", ["--filter", "@necodoc/api", "openapi", specPath], { stdio: "inherit" });

// The app serves the document with a relative server (its own origin); readers of the public
// docs run their own deployment.
const spec = JSON.parse(readFileSync(specPath, "utf8"));
spec.servers = [
  {
    url: "https://{host}/api/v1",
    description: "Your necodoc deployment",
    variables: { host: { default: "necodoc.example.com" } },
  },
];
writeFileSync(specPath, `${JSON.stringify(spec, null, 2)}\n`);

// Each SDK's README becomes its page; the READMEs are the single source.
const sdkPages = [
  { dir: "sdk-ts", slug: "typescript", title: "TypeScript SDK", order: 1 },
  { dir: "sdk-python", slug: "python", title: "Python SDK", order: 2 },
  { dir: "sdk-dotnet", slug: "dotnet", title: ".NET SDK", order: 3 },
  { dir: "sdk-java", slug: "java", title: "Java SDK", order: 4 },
];
for (const sdk of sdkPages) {
  const readme = readFileSync(join(root, `../../packages/${sdk.dir}/README.md`), "utf8")
    // The page has its own title.
    .replace(/^# .*\n+/, "");
  writeFileSync(
    join(root, `src/content/docs/reference/sdks/${sdk.slug}.md`),
    `---
title: ${sdk.title}
description: A typed client for /api/v1, generated from the OpenAPI document.
sidebar:
  order: ${sdk.order}
---

<!-- Generated by scripts/generate.ts from packages/${sdk.dir}/README.md. Edit that file. -->

${readme}`,
  );
}

console.log("devdocs generate: wrote the OpenAPI document and the SDK pages.");
