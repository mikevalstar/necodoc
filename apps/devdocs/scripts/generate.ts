// Build hook for generated content (ADR 0026, ADR 0030). Runs before `astro build` and `astro dev`.
//
// Writes the /api/v1 OpenAPI document from the API's code (`pnpm --filter @necodoc/api openapi`)
// into src/generated/openapi.json, which starlight-openapi renders as the API reference, and
// copies the TypeScript SDK's README into the SDK page. Nothing here is written by hand.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "src/generated/openapi.json");
mkdirSync(dirname(specPath), { recursive: true });

execFileSync("pnpm", ["--filter", "@necodoc/api", "openapi", specPath], { stdio: "inherit" });

// The app serves the document with a relative server (its own origin); readers of the public
// docs run their own deployment.
const spec = JSON.parse(readFileSync(specPath, "utf8"));
spec.servers = [
  {
    url: "https://{host}/api/v1",
    description: "Your necodoc deployment",
    variables: { host: { default: "necodoc.example.com" } },
  },
];
writeFileSync(specPath, `${JSON.stringify(spec, null, 2)}\n`);

const readme = readFileSync(join(root, "../../packages/sdk-ts/README.md"), "utf8")
  // The page has its own title.
  .replace(/^# .*\n+/, "");
writeFileSync(
  join(root, "src/content/docs/reference/sdks/typescript.md"),
  `---
title: TypeScript SDK
description: A typed client for /api/v1, generated from the OpenAPI document.
sidebar:
  order: 1
---

<!-- Generated by scripts/generate.ts from packages/sdk-ts/README.md. Edit that file. -->

${readme}`,
);

console.log("devdocs generate: wrote the OpenAPI document and the TypeScript SDK page.");
