import type { Latency, Results, Stats } from "./schema";

// Spec: docs/features/performance-benchmark.md (statistics, output).

const round = (n: number) => Math.round(n * 10) / 10;

/** Nearest-rank percentile over sorted samples. */
const percentile = (sorted: number[], p: number) =>
  sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1))] ?? 0;

export function stats(samples: readonly number[]): Stats {
  if (!samples.length)
    return { n: 0, mean: null, min: null, max: null, p50: null, p95: null, p99: null };
  const sorted = [...samples].sort((a, b) => a - b);
  return {
    n: sorted.length,
    mean: round(sorted.reduce((sum, v) => sum + v, 0) / sorted.length),
    min: round(sorted[0] ?? 0),
    max: round(sorted.at(-1) ?? 0),
    p50: round(percentile(sorted, 50)),
    p95: round(percentile(sorted, 95)),
    p99: round(percentile(sorted, 99)),
  };
}

const ms = (v: number | null) => (v === null ? "–" : `${Math.round(v)}`);
const row = (cells: (string | number)[]) => `| ${cells.join(" | ")} |`;
const statCells = (s: Stats) => [
  s.n,
  ms(s.p50),
  ms(s.p95),
  ms(s.p99),
  ms(s.mean),
  ms(s.min),
  ms(s.max),
];

function latencyTable(scenarios: Latency[]) {
  return [
    row([
      "Scenario",
      "Pages",
      "n",
      "p50",
      "p95",
      "p99",
      "mean",
      "min",
      "max",
      "queue p50",
      "run p50",
    ]),
    row(Array(11).fill("---")),
    ...scenarios.map((s) =>
      row([s.label, s.pages, ...statCells(s.roundTrip), ms(s.queueWait.p50), ms(s.run.p50)]),
    ),
  ].join("\n");
}

function breakdownTable(scenarios: Latency[]) {
  return [
    row(["Scenario", "Liquid", "Chromium", "Bands", "Stamping", "Finishing"]),
    row(Array(6).fill("---")),
    ...scenarios.map((s) =>
      row([
        s.label,
        ms(s.breakdown.liquidMs),
        ms(s.breakdown.chromiumMs),
        ms(s.breakdown.bandsMs),
        ms(s.breakdown.stampMs),
        ms(s.breakdown.finishMs),
      ]),
    ),
  ].join("\n");
}

export function markdown(r: Results) {
  const e = r.environment;
  const s = r.settings;
  const lines = [
    "# necodoc performance benchmark",
    "",
    `Generated by \`pnpm bench\` on ${r.startedAt.slice(0, 10)}. Method and caveats: [docs/features/performance-benchmark.md](../../../docs/features/performance-benchmark.md).${r.quick ? " **Quick run: not for publishing.**" : ""}`,
    "",
    "## Environment",
    "",
    `- ${e.cpu}, ${e.cores} cores, ${e.memoryGb} GB RAM, ${e.os}`,
    `- Node ${e.node}, Chromium ${e.chromium}, ${e.postgres.split(" on ")[0]} (private local cluster, default settings except max_connections=400), storage: ${e.storage}`,
    `- Commit ${e.gitSha.slice(0, 10)}${e.gitDirty ? " (uncommitted changes)" : ""}; load average before the run ${e.loadAverage.map((l) => l.toFixed(2)).join(" / ")}`,
    `- Latency: ${s.latencyWorkers} worker, RENDER_CONCURRENCY=${s.concurrency}, ${s.samples} samples after ${s.warmup} warm-up requests, one request at a time`,
    "",
    "## Latency (ms, client round trip through /api/v1)",
    "",
    latencyTable(r.latency),
    "",
    "Queue and run are the generation log's queue wait and worker run time (p50).",
    "",
    "### Where the time goes (mean ms, generation log)",
    "",
    breakdownTable(r.latency),
    "",
  ];
  if (r.archival) {
    lines.push(
      "## PDF/A-2b + PDF/UA overhead",
      "",
      latencyTable([r.archival.plain, r.archival.archival]),
      "",
      `p50 overhead: ${Math.round(r.archival.overheadP50Ms)} ms.`,
      "",
    );
  }
  lines.push(
    "## Cold vs warm Chromium (ms)",
    "",
    row(["", "n", "p50", "p95", "p99", "mean", "min", "max"]),
    row(Array(8).fill("---")),
    row(["Worker start to ready", ...statCells(r.coldWarm.workerStart)]),
    row(["First render (cold)", ...statCells(r.coldWarm.cold)]),
    row(["Warm render", ...statCells(r.coldWarm.warm)]),
    "",
    "## Batch throughput (designed surety bond)",
    "",
    row([
      "Workers",
      "Concurrency",
      "Rows",
      "Failed",
      "Wall (s)",
      "Docs/min",
      "Run p50",
      "Queue wait p50",
    ]),
    row(Array(8).fill("---")),
    ...r.throughput.map((t) =>
      row([
        t.workers,
        t.concurrency,
        t.rows,
        t.failed,
        (t.wallMs / 1000).toFixed(1),
        Math.round(t.docsPerMinute),
        ms(t.run.p50),
        ms(t.queueWait.p50),
      ]),
    ),
    "",
  );
  return lines.join("\n");
}
